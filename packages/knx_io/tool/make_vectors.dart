// Writes ../../test-vectors/ft12.json from the inputs below and this package's
// implementation. Other implementations (python/kberry) test against the file.
// Run: dart run tool/make_vectors.dart
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:knx/knx.dart' show hexOf;
import 'package:knx_io/knx_io.dart';

String _hex(List<int> b) => hexOf(Uint8List.fromList(b)).replaceAll(' ', '').toLowerCase();
List<int> _bytes(String h) => [for (var i = 0; i < h.length; i += 2) int.parse(h.substring(i, i + 2), radix: 16)];

Map<String, Object?> _event(Ft12Event e) => switch (e) {
  Ft12AckEvent() => {'type': 'ack'},
  Ft12FixedEvent(:final control) => {'type': 'fixed', 'control': control},
  Ft12DataEvent(:final control, :final data) => {'type': 'data', 'control': control, 'data': _hex(data)},
};

void main() {
  final encode = [
    {'name': 'read serial number, fcb clear', 'data': 'fc000001 0b1001', 'fcb': false},
    {'name': 'PEI identify, fcb set', 'data': 'a7', 'fcb': true},
    {'name': 'switch to link layer (PID 52 = 0x00)', 'data': 'f6000801341001 00', 'fcb': true},
    {'name': 'L_Data.req GroupValueWrite 1/2/3 = 0', 'data': '1100bce000000a03010080', 'fcb': false},
  ];
  final decode = [
    {
      'name': 'ack, answer in two pieces, reset',
      'chunks': ['e5680e0e68d3fb00', '00010b100100c500000000b016', '10404016'],
    },
    {
      'name': 'garbage and a wrong checksum are skipped',
      'chunks': ['00ff6802026873a70016e5'],
    },
    {
      'name': 'L_Data.ind in one piece',
      'chunks': ['680c0c68f32900bce011050a030100815d16'],
    },
    {
      'name': 'fixed frame with mismatching control bytes',
      'chunks': ['10404116e5'],
    },
    {
      'name': 'incomplete frame stays buffered',
      'chunks': ['680c0c68f32900bce0'],
    },
  ];
  final busmon = [
    {'name': 'data frame with status and timestamp', 'cemi': '2b0703010004021234bc110509 01e100813f'},
    {'name': 'acknowledgement', 'cemi': '2b00cc'},
    {'name': 'repeated data frame', 'cemi': '2b0703010004021234 9c11050901e100811f'},
    {'name': 'wrong checksum', 'cemi': '2b0703010004021234bc11050901e100813a'},
    {'name': 'frame error in status', 'cemi': '2b0703018004021234bc11050901e100813f'},
    {'name': 'truncated', 'cemi': '2b0703010004021234bc1105'},
  ];
  final out = {
    'about':
        'FT1.2 (IEC 60870-5) and cEMI test vectors for the Weinzierl kBerry and similar modules. '
        'Hex without spaces. Generated by packages/knx_io/tool/make_vectors.dart.',
    'ack': ft12Ack,
    'reset': _hex(ft12Reset),
    'encode': [
      for (final e in encode)
        {
          ...e,
          'data': (e['data']! as String).replaceAll(' ', ''),
          'frame': _hex(ft12Frame(_bytes((e['data']! as String).replaceAll(' ', '')), fcb: e['fcb']! as bool)),
        },
    ],
    'decode': [
      for (final d in decode)
        () {
          final decoder = Ft12Decoder();
          final chunks = [for (final c in d['chunks']! as List) (c as String).replaceAll(' ', '')];
          final events = [for (final c in chunks) ...decoder.add(_bytes(c))];
          return {
            'name': d['name'],
            'chunks': chunks,
            'events': events.map(_event).toList(),
            'skipped': decoder.skipped,
          };
        }(),
    ],
    'busmonToLData': [
      for (final b in busmon)
        () {
          final cemi = b['cemi']!.replaceAll(' ', '');
          final l = busmonToLData(Uint8List.fromList(_bytes(cemi)));
          return {'name': b['name'], 'cemi': cemi, 'ldata': l == null ? null : _hex(l)};
        }(),
    ],
    'busmonCounters': () {
      final c = BusmonCounters();
      final frames = [for (final b in busmon) b['cemi']!.replaceAll(' ', '')];
      for (final f in frames) {
        c.add(Uint8List.fromList(_bytes(f)));
      }
      return {'frames': frames, 'counters': c.toJson()};
    }(),
  };
  File('../../test-vectors/ft12.json').writeAsStringSync('${const JsonEncoder.withIndent('  ').convert(out)}\n');
}
